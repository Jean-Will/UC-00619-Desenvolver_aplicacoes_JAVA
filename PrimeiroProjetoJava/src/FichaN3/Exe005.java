package FichaN3;

/**
 *. Contagem decrescente
    Cria um programa que mostre os números de 10 até 1 
    * em ordem decrescente usando um for
 * 
 * @author jeanw
 */
public class Exe005 {

    /**
     * @param args the command line arguments
     */
    public static void main(String[] args) {
        for (int i = 10; i > 0; i--) {
            System.out.print(i + "\n");
        }
    }
    
}
