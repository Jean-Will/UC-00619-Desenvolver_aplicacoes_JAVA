package FichaN3;

/**
 *
 *  Números de 1 a 10
    Cria um programa que mostre no ecrã os
    * números de 1 até 10 usando um ciclo for.
 * @author jeanw
 */
public class Exe001 {

    /**
     * @param args the command line arguments
     */
    public static void main(String[] args) {
        for (int i = 1; i < 11; i++) {
            System.out.print(i + " " + "\n");
        }
    }
    
}
